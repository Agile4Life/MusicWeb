import { test, expect } from '@playwright/test'

test.use({ channel: 'chrome' })

test('places the selection on the left and adds YouTube videos to a battle', async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('has_seen_onboarding', 'true'))
  await page.route('**/api/auth/session', route => route.fulfill({ json: {} }))
  await page.route('**/api/song-battles*', route => route.fulfill({ json: { decks: [], total: 0, page: 1, pageSize: 12 } }))
  const videos = [1, 2].map(i => ({ id: `yt-video${i}`, youtube_id: `video${i}`, source: 'youtube', title: `Video ${i}`, artist: 'Artist' }))
  await page.route('**/api/search?**', route => {
    expect(new URL(route.request().url()).searchParams.get('source')).toBe('youtube')
    return route.fulfill({ json: { youtube: videos, spotify: [] } })
  })
  await page.route('**/api/spotify/search?**', () => { throw new Error('Search should use YouTube') })
  await page.route('https://www.youtube.com/embed/**', route => route.fulfill({ contentType: 'text/html', body: '<p>Video fixture</p>' }))
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('/spotify-lab')
  await page.getByRole('button', { name: 'Tạo cuộc đấu', exact: true }).click()
  const pool = page.getByRole('complementary', { name: 'Sân khấu của bạn.' })
  const source = page.getByRole('region', { name: 'Bắt đầu từ gu nhạc của bạn.' })
  const poolBox = await pool.boundingBox()
  const sourceBox = await source.boundingBox()
  expect(poolBox!.x + poolBox!.width).toBeLessThanOrEqual(sourceBox!.x + 1)
  expect(sourceBox!.width).toBeGreaterThan(poolBox!.width)
  await page.getByLabel('Tìm bài hát', { exact: true }).fill('music video')
  await page.getByRole('button', { name: 'Thêm tất cả' }).click()
  await expect(page.getByText('2 bài đã chọn', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Nghe bài đã chọn Video 1', exact: true }).click()
  await expect(page.getByTitle('YouTube: Video 1', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Đóng trình nghe thử' }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  const mobilePool = await pool.boundingBox()
  const mobileSource = await source.boundingBox()
  expect(mobilePool!.y + mobilePool!.height).toBeLessThanOrEqual(mobileSource!.y + 1)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByRole('button', { name: 'Bắt đầu đọ nhạc' }).click()
  await expect(page.locator('article iframe[src*="youtube.com/embed/"]')).toHaveCount(2)
})
