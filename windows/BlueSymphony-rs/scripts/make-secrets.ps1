<#
.SYNOPSIS
    Generates config/secrets.toml from MusicWeb/.env.local or .env.
#>
$ErrorActionPreference = "Stop"

$scriptDir = Split-Path -Parent $MyInvocation.MyCommand.Path
$rsRoot = Split-Path -Parent $scriptDir
$webRoot = Split-Path -Parent (Split-Path -Parent $rsRoot)
$outFile = Join-Path $rsRoot "config\secrets.toml"

$envCandidates = @(
    (Join-Path $webRoot ".env.local"),
    (Join-Path $webRoot ".env")
)

$envFile = $envCandidates | Where-Object { Test-Path $_ } | Select-Object -First 1
if (-not $envFile) {
    Write-Warning "No .env.local or .env found in $webRoot. Creating empty config/secrets.toml from example."
    Copy-Item (Join-Path $rsRoot "config\secrets.example.toml") $outFile -Force
    exit 0
}

$vars = @{}
foreach ($line in Get-Content $envFile) {
    $trimmed = $line.Trim()
    if (-not $trimmed -or $trimmed.StartsWith("#")) { continue }
    $idx = $trimmed.IndexOf("=")
    if ($idx -le 0) { continue }
    $k = $trimmed.Substring(0, $idx).Trim()
    $v = $trimmed.Substring($idx + 1).Trim()
    if (($v.StartsWith('"') -and $v.EndsWith('"')) -or ($v.StartsWith("'") -and $v.EndsWith("'"))) {
        $v = $v.Substring(1, $v.Length - 2)
    }
    $vars[$k] = $v
}

$supabaseUrl = $vars["NEXT_PUBLIC_SUPABASE_URL"]
$supabaseKey = $vars["NEXT_PUBLIC_SUPABASE_ANON_KEY"]
if (-not $supabaseKey) { $supabaseKey = $vars["NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY"] }

function Escape-Toml([string]$s) {
    if (-not $s) { return "" }
    return $s.Replace("\", "\\").Replace('"', '\"')
}

$content = @"
# Auto-generated by scripts/make-secrets.ps1 — do not commit.
supabase_url = "$(Escape-Toml $supabaseUrl)"
supabase_anon_key = "$(Escape-Toml $supabaseKey)"
"@

Set-Content -Path $outFile -Value $content -Encoding UTF8
Write-Host "Wrote config/secrets.toml (configured: $([bool]($supabaseUrl -and $supabaseKey)))"

